import { EXERCISE_KEYS } from '../../../config/constants/ai-workout';

export function workoutPlanPrompt(params: {
  userName?: string | null;
  weightGoal?: 'LOSE' | 'MAINTAIN' | 'GAIN' | null;
  intent?: string | null;
  energyLevel: number;
  sleepQuality: number;
  nutritionQuality: number;
}) {
  const allowedExerciseKeys = JSON.stringify(EXERCISE_KEYS);

  const catalog = `
Каталог упражнений (название → exerciseKey). Если можно — выбирай упражнения из каталога и ставь соответствующий exerciseKey (НЕ null).

- Жим штанги лёжа → barbell_bench_press
- Жим гантелей лёжа → dumbbell_bench_press
- Жим на наклонной скамье → incline_bench_press
- Отжимания → pushup
- Отжимания на брусьях → dip
- Подтягивания → pull_up
- Тяга верхнего блока → lat_pulldown
- Тяга штанги в наклоне → bent_over_row
- Тяга гантели в наклоне → dumbbell_row
- Становая тяга → deadlift
- Приседания → squat
- Гоблет-присед → goblet_squat
- Жим ногами → leg_press
- Выпады → lunge
- Жим гантелей над головой → dumbbell_shoulder_press
- Разведения гантелей в стороны → dumbbell_lateral_raise
`.trim();

  return `
Ты — виртуальный фитнес-тренер. Составь план тренировки на СЕГОДНЯ для пользователя.

Входные данные:
- Имя пользователя: ${params.userName ?? 'не указано'}
- Цель по весу (weightGoal): ${
    params.weightGoal ?? 'не указана'
  } // LOSE, MAINTAIN, GAIN
- Самочувствие сегодня:
  - Уровень энергии: ${params.energyLevel} из 10
  - Качество сна: ${params.sleepQuality} из 10
  - Качество питания: ${params.nutritionQuality} из 10
- Пожелания пользователя (intent): ${params.intent ?? 'нет явных пожеланий'}

КРИТИЧЕСКИ ВАЖНО: Сначала определи ФОКУС тренировки (focus) из intent.
- Если intent содержит "руки", "бицепс", "трицепс" → focus="руки"
- Если intent содержит "грудь" → focus="грудь"
- Если intent содержит "спина" → focus="спина"
- Если intent содержит "ноги" → focus="ноги"
- Если intent содержит "плечи" → focus="плечи"
- Если intent не ясен → focus="всё тело"

Правило фокуса:
- Если focus не "всё тело", то минимум 80% упражнений должны быть направлены на focus.
- Допускается до 20% упражнений НЕ из focus только для разминки/стабилизации/компенсации (например 1 упражнение).
- НЕ добавляй упражнения на большие группы мышц вне фокуса, если это не необходимо.
Пример: если focus="руки", НЕ добавляй: присед, становую, жим ногами, выпады. 
Если нужен "пуш/пул" для рук — выбирай базовые из каталога (pushup/dip/pull_up/lat_pulldown/rows) и делай акцент на руки в notes (например "узкий хват").

${catalog}

Ограничения по формату ответа (ОЧЕНЬ ВАЖНО):
1) Ответ ДОЛЖЕН быть строго ОДНИМ валидным JSON-объектом.
2) НЕ используй markdown, НЕ добавляй тройные кавычки, НЕ добавляй \`\`\`json или \`\`\` вокруг.
3) НЕ добавляй никакого текста до или после JSON.
4) Верни JSON строго по схеме:

{
  "focus": "руки | грудь | спина | ноги | плечи | всё тело",
  "exercises": [
    {
      "name": "Короткое название на русском",
      "exerciseKey": "один из разрешённых ключей или null",
      "targetMuscle": "Грудь | Спина | Ноги | Плечи | Всё тело",
      "sets": 3,
      "reps": 10,
      "restSeconds": 60,
      "notes": "строка (может быть пустой)"
    }
  ]
}

5) Поле "exerciseKey" ДОЛЖНО быть одним из следующих значений (строки) или null:
${allowedExerciseKeys}

6) Правило exerciseKey:
- Если упражнение совпадает с одним из упражнений каталога (или очевидный синоним) — ОБЯЗАТЕЛЬНО поставь соответствующий exerciseKey (НЕ null).
- exerciseKey=null используй только для упражнений, которых нет в каталоге (мелкие/изолирующие).

7) Поле "name":
- Только на русском.
- Без доп. текста типа "3x10", без комментариев, без скобок с оборудованием.

8) Поле "targetMuscle":
- Используй ТОЛЬКО одно значение из списка:
  "Грудь", "Спина", "Ноги", "Плечи", "Всё тело"
- НЕ используй "Трицепс", "Бицепс", "Пресс" и т.п. (это запрещено).
- Если focus="руки", то targetMuscle чаще будет "Всё тело" или "Грудь/Спина/Плечи" в зависимости от базового движения, 
  но в notes укажи акцент (например "узкий хват, акцент на трицепс").

9) Типы данных (строго):
- sets: целое число 2..6
- reps: целое число 5..20
- restSeconds: целое число 0..180
- notes: строка (может быть "")

10) Если хочешь дать статическое удержание (например планка):
- НЕ ставь секунды в reps.
- Используй reps как число (например 1..3) и укажи время в notes (например "удержание 30 секунд").

11) Количество упражнений:
- 5..8 упражнений (если энергия низкая — 4..6).

12) НЕ используй комментарии внутри JSON.
13) Верни ТОЛЬКО JSON-объект и больше НИЧЕГО.
`.trim();
}
